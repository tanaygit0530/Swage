import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { MCP_SERVER_DESCRIPTION, MCP_SERVER_NAME } from '../../src/client/setup';
import {
  APPROVAL_TOOLS,
  DEFERRED_TOOLS,
  EDITOR_TOOLS,
  HOT_TOOLS,
  TOOL_NAMES,
} from '../../src/mcp/tools/index';

const registration = JSON.parse(readFileSync('trueforge/mcp/editor-tools.json', 'utf8')) as {
  manifest: {
    name: string;
    url: string;
    description: string;
    auth: { headers: Record<string, string> };
  };
  tools: { preload: string[]; deferred: string[]; require_approval: string[] };
};
const main = JSON.parse(readFileSync('trueforge/agents/main.agent.json', 'utf8')) as {
  mcp_servers: {
    name: string;
    enable_tools: string[];
    preload: boolean;
    preload_tools: string[];
    require_approval_for_tools: string[];
  }[];
};
const inline = JSON.parse(
  readFileSync('trueforge/agents/inline.agent.json', 'utf8'),
) as typeof main;

describe('tool configuration', () => {
  it('has nine tools: five hot, four deferred, two gated by name', () => {
    expect(EDITOR_TOOLS).toHaveLength(9);
    expect(TOOL_NAMES).toHaveLength(9);
    expect(DEFERRED_TOOLS).toEqual(['repo_map', 'get_symbol', 'run_tests', 'run_command']);
    expect(APPROVAL_TOOLS).toEqual(['submit_change_set', 'run_command']);
  });

  it('main agent manifest preloads the hot tools, defers the rest and gates submit and run_command', () => {
    const server = main.mcp_servers[0];
    expect(server?.name).toBe(MCP_SERVER_NAME);
    expect(server?.enable_tools).toEqual(['@all']);
    expect(server?.preload).toBe(false);
    expect(server?.preload_tools).toEqual([...HOT_TOOLS]);
    expect(server?.require_approval_for_tools).toEqual([...APPROVAL_TOOLS]);
  });

  it('inline agent only enables tools that exist', () => {
    for (const t of inline.mcp_servers[0]?.enable_tools ?? []) expect(TOOL_NAMES).toContain(t);
  });

  it('editor-tools.json matches the server and holds no secret', () => {
    expect(registration.manifest.name).toBe(MCP_SERVER_NAME);
    expect(registration.manifest.description).toBe(MCP_SERVER_DESCRIPTION);
    expect(registration.manifest.url).toBe('http://127.0.0.1:<port>/mcp');
    expect(registration.manifest.auth.headers['Authorization']).toBe(
      'Bearer <token generated by the extension>',
    );
    expect(registration.tools.preload).toEqual([...HOT_TOOLS]);
    expect(registration.tools.deferred).toEqual(DEFERRED_TOOLS);
    expect(registration.tools.require_approval).toEqual([...APPROVAL_TOOLS]);
  });
});
