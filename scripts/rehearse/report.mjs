// `node scripts/rehearse.mjs report`: builds docs/EVIDENCE.md from docs/evidence/baseline and every
// docs/evidence/<run-id>/ (run.json, runs/*.json), with a table of runs, success rates, medians
// and the exact Swage commit of each rehearsal. Hand-written findings (fixes and limitations) come
// from docs/evidence/notes.md and are included as they are.
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import * as path from 'node:path';

const median = (xs) => {
  const v = xs.filter((x) => typeof x === 'number').sort((a, b) => a - b);
  if (v.length === 0) return undefined;
  const m = Math.floor(v.length / 2);
  return v.length % 2 ? v[m] : Math.round((v[m - 1] + v[m]) / 2);
};
const s = (ms) => (ms === undefined ? '–' : `${(ms / 1000).toFixed(1)} s`);
const cell = (t) =>
  String(t ?? '')
    .replace(/\|/g, '\\|')
    .replace(/\n/g, ' ');

export async function main({ repo }) {
  const root = path.join(repo, 'docs', 'evidence');
  const baseline = JSON.parse(readFileSync(path.join(root, 'baseline', 'baseline.json'), 'utf8'));
  const rehearsals = readdirSync(root)
    .filter((d) => existsSync(path.join(root, d, 'run.json')))
    .sort()
    .map((d) => {
      const meta = JSON.parse(readFileSync(path.join(root, d, 'run.json'), 'utf8'));
      const dir = path.join(root, d, 'runs');
      const runs = existsSync(dir)
        ? readdirSync(dir)
            .sort()
            .map((f) => JSON.parse(readFileSync(path.join(dir, f), 'utf8')))
        : [];
      return { dir: d, meta, runs };
    })
    .filter((r) => r.runs.length > 0);

  const out = [
    '# Evidence: rehearsals on Flask 3.1.3',
    '',
    "Generated by `node scripts/rehearse.mjs report` from `docs/evidence/`. Every run used the problem statement's exact instructions, real models through TrueForge, and the real extension in a test VS Code opened on a clean Flask clone (blueprint sections 10, 11 and 17). Run logs, with secrets redacted, are in `docs/evidence/<run-id>/logs/`.",
    '',
    '**Status:** testing is deferred until the build is complete, so this file holds the rehearsals run so far, including runs made before fixes they led to (see the findings at the end). The final rehearsal will be added by `node scripts/rehearse.mjs run` and this file regenerated.',
    '',
    '## Baseline',
    '',
    `Flask ${baseline.flask.tag} (commit \`${baseline.flask.commit}\`), cloned into a temp folder outside the repository; Python ${baseline.python}, pytest ${baseline.pytest}, dependencies pinned to Flask's \`uv.lock\` (${baseline.testDeps.join(', ')}).`,
    '',
    `- Full suite before any change: **${baseline.suite.summary}**`,
    `- \`tests/test_cli.py\`: **${baseline.testCli.summary}**`,
    '',
  ];

  for (const r of rehearsals) {
    const { meta, runs } = r;
    const by = (t) => runs.filter((x) => x.task === t);
    // Medians cover passed runs only: a failed run has no diff time or token count to speak of.
    const passed = (xs) => xs.filter((x) => x.ok);
    const rate = (xs) => `${xs.filter((x) => x.ok).length} of ${xs.length}`;
    out.push(
      `## Rehearsal ${meta.runId}`,
      '',
      `Swage commit \`${meta.swageCommit}\`${meta.swageDirty ? ' (with uncommitted changes)' : ''}; TrueForge ${meta.trueforge}; profiles: ${meta.profiles.map((p) => `${p.name} \`${p.trueforgeModel}\``).join(', ')}.`,
      '',
      '| Task | Runs passed | Median time (passed runs) | Median tokens (passed runs) | Notes |',
      '| --- | --- | --- | --- | --- |',
    );
    const a = by('A');
    const b = by('B');
    const c = by('C');
    const cancel = by('cancel');
    const undo = by('undo');
    if (cancel.length)
      out.push(
        `| Cancel before A | ${rate(cancel)} | Stop to UI ${median(passed(cancel).map((x) => x.stopToUiMs))} ms | – | ${cell(cancel.map((x) => x.summary).join('; '))} |`,
      );
    if (a.length)
      out.push(
        `| A inline edit | ${rate(a)} | instruction to diff ${s(median(passed(a).map((x) => x.instructionToDiffMs)))} | ${median(passed(a).map((x) => x.tokens)) ?? '–'} | blocks: ${a.map((x) => x.blocks ?? '–').join(', ')} |`,
      );
    if (b.length)
      out.push(
        `| B agent mode | ${rate(b)} | instruction to review ${s(median(passed(b).map((x) => x.toReviewMs)))} | ${median(passed(b).map((x) => x.tokens)) ?? '–'} | files: ${b.map((x) => (x.files ? x.files.length : 0)).join(', ')} |`,
      );
    if (undo.length) out.push(`| Double undo | ${rate(undo)} | – | – | ${cell(undo[0].summary)} |`);
    if (c.length)
      out.push(
        `| C fallback | ${rate(c)} | start to diff ${s(median(passed(c).map((x) => x.startToDiffMs)))} | ${median(passed(c).map((x) => x.tokens)) ?? '–'} | max event-loop lag ${median(passed(c).map((x) => x.maxEventLoopLagMs))} ms |`,
      );
    out.push(
      '',
      '### Runs',
      '',
      '| Run | Result | Time | Tokens | Tool calls | Summary |',
      '| --- | --- | --- | --- | --- | --- |',
    );
    for (const x of runs) {
      const time = x.instructionToDiffMs ?? x.toReviewMs ?? x.startToDiffMs ?? x.stopToUiMs;
      const tools = x.toolSequence ? x.toolSequence.join(' → ') : '–';
      out.push(
        `| ${x.id} | ${x.ok ? 'pass' : '**fail**'} | ${x.task === 'cancel' ? `${time} ms` : s(time)} | ${x.tokens ?? '–'} | ${cell(tools)} | ${cell(x.summary)} |`,
      );
    }
    if (b.length) {
      out.push('', '### Task B: files found and retrieval', '');
      for (const x of b) {
        out.push(
          `- **${x.id}**: files ${x.files ? x.files.map((f) => `\`${f.path}\` (${f.kind}, ${f.blocks} block(s))`).join(', ') : 'none'}; retrieval hits: ${x.retrievalHits?.length ? x.retrievalHits.map((h) => `\`${h}\``).join(', ') : 'none'}; \`tests/test_cli.py\` after Apply: ${x.testCli?.summary ?? '–'}; full suite: ${x.testsSuite?.summary ?? '–'}.`,
        );
      }
    }
    if (c.length) {
      out.push('', '### Task C: the switch', '');
      for (const x of c)
        out.push(
          `- **${x.id}**: ${cell(x.switches?.join('; ') || 'no switch')}; primary failure: ${cell(x.primaryFailure ? `${x.primaryFailure.kind}, ${x.primaryFailure.reason}` : '–')}; the primary got ${x.primaryRequests ?? '?'} request(s); \`git status\` after Reject all: ${x.gitStatusAfter === '' ? 'clean' : `\`${cell(x.gitStatusAfter)}\``}.`,
        );
    }
    out.push('');
  }

  const notes = path.join(root, 'notes.md');
  if (existsSync(notes)) out.push(readFileSync(notes, 'utf8').trim(), '');
  writeFileSync(path.join(repo, 'docs', 'EVIDENCE.md'), `${out.join('\n')}\n`);
  console.log(`Wrote docs/EVIDENCE.md (${rehearsals.length} rehearsal(s))`);
}
